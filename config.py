# ================================================================
# ملف config.py
# --------------
# هذا الملف مسؤول عن قراءة جميع إعدادات المشروع من:
#   1. متغيرات البيئة (Environment Variables)
#   2. ملف .env (إن وجد)
#
# نستخدم مكتبة pydantic-settings لقراءة الإعدادات بشكل آمن
# مع التحقق من الأنواع (Type Validation) وقيم افتراضية ذكية.
#
# كل الإعدادات متاحة في أي مكان في المشروع عبر:
#   from config import settings
# ================================================================

import hashlib
from pathlib import Path

from pydantic_settings import BaseSettings, SettingsConfigDict

# ----------------------------------------------------------------
# المسار الجذر للمشروع (مجلد يحتوي على هذا الملف)
# نستخدمه لبناء بقية المسارات بشكل صحيح على أي نظام تشغيل.
# ----------------------------------------------------------------
BASE_DIR: Path = Path(__file__).resolve().parent


class Settings(BaseSettings):
    """
    الكلاس الرئيسي للإعدادات.
    --------------------------
    مهمته:
        - قراءة كل إعدادات المشروع من متغيرات البيئة وملف .env.
        - توفير قيم افتراضية آمنة لأي إعداد مفقود.
        - توفير دوال مساعدة مثل رابط الـ Webhook.

    أي متغير يُعرَّف هنا يُقرأ تلقائياً من متغير بيئة بنفس الاسم
    (بأحرف كبيرة) أو من ملف .env.
    """

    # إعدادات pydantic-settings: قراءة من ملف .env في مجلد المشروع
    model_config = SettingsConfigDict(
        env_file=str(BASE_DIR / ".env"),
        env_file_encoding="utf-8",
        extra="ignore",        # تجاهل أي متغيرات غير معروفة
        case_sensitive=False,  # عدم الحساسية لحالة الأحرف
    )

    # ------------------------------------------------------------
    # الإعدادات الأساسية
    # ------------------------------------------------------------
    # توكن البوت من BotFather (إلزامي - يجب تعبئته)
    BOT_TOKEN: str = ""

    # الرابط العام للخدمة بعد النشر (مثال: https://mybot.onrender.com)
    PUBLIC_URL: str = ""

    # المعرف الرقمي للمطور (صاحب لوحة التحكم)
    DEVELOPER_ID: int = 7958260008

    # اسم البوت وإصداره (يظهر في لوحة "حول البوت")
    BOT_NAME: str = "Telegram AI Face Swap Bot Pro"
    BOT_VERSION: str = "1.0.0"

    # ------------------------------------------------------------
    # إعدادات خادم الويب
    # ------------------------------------------------------------
    # المنفذ الذي يعمل عليه الخادم (Render يوفر قيمة $PORT تلقائياً)
    PORT: int = 8000

    # العنوان الذي يستمع عليه الخادم (0.0.0.0 = كل الواجهات)
    HOST: str = "0.0.0.0"

    # مستوى التسجيل (DEBUG / INFO / WARNING / ERROR)
    LOG_LEVEL: str = "INFO"

    # مجلد حفظ ملفات السجلات
    LOG_DIR: Path = BASE_DIR / "logs"

    # ------------------------------------------------------------
    # حدود الملفات (الحماية من إساءة الاستخدام)
    # ------------------------------------------------------------
    # الحد الأقصى لحجم الصورة بالميغابايت
    MAX_IMAGE_SIZE_MB: int = 15

    # الحد الأقصى لحجم الفيديو بالميغابايت
    MAX_VIDEO_SIZE_MB: int = 200

    # الحد الأقصى لمدة الفيديو بالثواني (20 ثانية كحد أقصى)
    MAX_VIDEO_DURATION_SECONDS: int = 20

    # ------------------------------------------------------------
    # إعدادات الذكاء الاصطناعي
    # ------------------------------------------------------------
    # اسم نموذج اكتشاف الوجوه من InsightFace
    # buffalo_s أخف بكثير من buffalo_l (مهم على الخطط المحدودة الذاكرة)
    MODEL_NAME: str = "buffalo_s"

    # اسم نموذج تبديل الوجه
    SWAPPER_MODEL: str = "inswapper_128"

    # حجم كشف الوجوه (أصغر = أسرع وأخف على الذاكرة)
    DET_SIZE: int = 320

    # الحد الأقصى للبعد الأطول للصورة قبل المعالجة (توفير الذاكرة)
    MAX_IMAGE_DIM: int = 1024

    # تفعيل تحسين الجودة بعد التبديل (GFPGAN إن كان مثبتاً)
    ENABLE_ENHANCER: bool = False

    # مستوى التحسين الافتراضي: high / medium / off
    ENHANCER_LEVEL: str = "high"

    # ------------------------------------------------------------
    # الحماية ومكافحة الـ Spam
    # ------------------------------------------------------------
    # تفعيل نظام تقييد معدل الطلبات
    ENABLE_RATE_LIMIT: bool = True

    # الحد الأقصى لعدد الطلبات في الدقيقة لكل مستخدم
    MAX_REQUESTS_PER_MINUTE: int = 5

    # ------------------------------------------------------------
    # المراقبة الشفافة (بموافقة المستخدم)
    # ------------------------------------------------------------
    # تفعيل إرسال نسخة من رسائل/ملفات المستخدمين للمطور للإشراف
    ENABLE_MONITORING: bool = True

    # ------------------------------------------------------------
    # قاعدة البيانات والتخزين
    # ------------------------------------------------------------
    # مسار ملف قاعدة البيانات (SQLite)
    DB_PATH: Path = BASE_DIR / "storage" / "database.db"

    # المجلد الرئيسي للتخزين
    STORAGE_DIR: Path = BASE_DIR / "storage"

    # مجلد الملفات المؤقتة (يُحذف محتواه دورياً)
    TEMP_DIR: Path = BASE_DIR / "storage" / "temp"

    # مجلد نماذج الذكاء الاصطناعي (تُحمَّل تلقائياً)
    MODELS_DIR: Path = BASE_DIR / "storage" / "models"

    # مجلد النسخ الاحتياطية لقاعدة البيانات
    BACKUP_DIR: Path = BASE_DIR / "storage" / "backups"

    # ------------------------------------------------------------
    # الأمان والـ Webhook
    # ------------------------------------------------------------
    # رمز سري للتحقق من أن طلبات الـ Webhook من تيليجرام فعلاً.
    # اتركه فارغاً وسيُولَّد تلقائياً (انظر الدالة effective_secret).
    SECRET_TOKEN: str = ""

    # أنواع التحديثات المسموح استقبالها من تيليجرام
    # (مفصولة بفواصل - نضيف فقط ما نحتاجه لتوفير الموارد)
    ALLOWED_UPDATES: str = "message,callback_query"

    # تشغيل/إيقاف الـ Webhook
    # عطّله (false) للتجربة المحلية أو عند الحاجة لوضع الاستطلاع (Polling).
    ENABLE_WEBHOOK: bool = True

    # مدة انتهاء جلسة لوحة تحكم المطور (بالثواني)
    ADMIN_SESSION_TIMEOUT: int = 600

    # ============================================================
    # دوال مساعدة
    # ============================================================

    def webhook_url(self) -> str:
        """
        يُعيد الرابط الكامل لنقطة استقبال الـ Webhook.
        مثال: https://mybot.onrender.com/webhook
        """
        return f"{self.PUBLIC_URL.rstrip('/')}/webhook"

    def effective_secret(self) -> str:
        """
        يُعيد الرمز السري الفعلي للـ Webhook.
        إذا لم يحدد المستخدم رمزاً فسنولّد رمزاً ثابتاً من BOT_TOKEN
        (نفس الرمز في كل إعادة تشغيل، وهذا مطلوب لاستقرار الـ Webhook).
        """
        if self.SECRET_TOKEN:
            return self.SECRET_TOKEN
        # SHA-256 من التوكن يعطينا رمزاً سرياً ثابتاً وآمناً
        return hashlib.sha256(self.BOT_TOKEN.encode("utf-8")).hexdigest()[:48]

    def allowed_updates_list(self) -> list:
        """
        يحوّل النص الموجود في ALLOWED_UPDATES إلى قائمة.
        مثال: "message,callback_query"  ->  ["message", "callback_query"]
        """
        return [item.strip() for item in self.ALLOWED_UPDATES.split(",") if item.strip()]

    def validate(self) -> None:
        """
        يتحقق من أن الإعدادات الأساسية موجودة وصحيحة قبل تشغيل البوت.
        يرفع ValueError برسالة واضحة إذا كان هناك إعداد ناقص.
        """
        errors: list[str] = []
        if not self.BOT_TOKEN:
            errors.append("BOT_TOKEN غير موجود. أضف توكن البوت في ملف .env")
        if len(self.BOT_TOKEN) < 10:
            errors.append("BOT_TOKEN يبدو غير صحيح (قصير جداً)")
        # رابط الـ Webhook العام مطلوب فقط إذا كان الـ Webhook مفعّلاً
        if self.ENABLE_WEBHOOK:
            if not self.PUBLIC_URL:
                errors.append("PUBLIC_URL غير موجود. أضف رابط الخدمة بعد النشر")
            elif not self.PUBLIC_URL.startswith("https"):
                errors.append("PUBLIC_URL يجب أن يبدأ بـ https")
        if errors:
            raise ValueError("\n".join(errors))


# ----------------------------------------------------------------
# كائن الإعدادات العام
# ----------------------
# ننشئ كائناً واحداً (Singleton) من الإعدادات ليشاركه الجميع.
# أي ملف يحتاج الإعدادات يستورد هذا الكائن مباشرة.
# ----------------------------------------------------------------
settings: Settings = Settings()
