# ================================================================
# ملف states.py
# --------------
# هذا الملف يحدد حالات المحادثة (Conversation States) للبوت.
#
# لماذا نحتاج الحالات؟
# --------------------
# بعض العمليات تحتاج أكثر من خطوة (مثلاً: تبديل صورة يتطلب
# صورة الوجه ثم الصورة الهدف). حالة المحادثة تسمح للبوت
# بتذكر "أين وصل المستخدم" حتى يرسل الخطوة التالية.
#
# مثال: المستخدم يضغط "تبديل صورة" => ندخل حالة
# IMAGE_SWAP_SOURCE. عندما يرسل الصورة الأولى ننتقل إلى
# IMAGE_SWAP_TARGET ونطلب منه الصورة الثانية.
#
# نستخدم أرقاماً صحيحة كقيم للحالات لأنها أسرع وأسهل في
# المقارنة من النصوص، وتفصل بين حالات الصورة والفيديو
# والإدارة لمنع أي تداخل.
# ================================================================


class ConversationState:
    """
    كلاس ثابت يحتوي على جميع حالات المحادثة.
    -----------------------------------------
    كل متغير هنا هو قيمة رقمية فريدة تمثل حالة معينة.
    نستخدم class variables بدلاً من Enum لسهولة الاستخدام
    والتوافق مع مكتبة python-telegram-bot.
    """

    # ============================================================
    # حالات تبديل الصور
    # ============================================================

    # في انتظار صورة الوجه (المصدر) لتبديل الصور
    IMAGE_SWAP_SOURCE: int = 10

    # في انتظار الصورة الهدف (التي سيُوضع فيها الوجه)
    IMAGE_SWAP_TARGET: int = 11

    # ============================================================
    # حالات تبديل الفيديو
    # ============================================================

    # في انتظار صورة الوجه (المصدر) لتبديل الفيديو
    VIDEO_SWAP_SOURCE: int = 20

    # في انتظار الفيديو الهدف (الذي سيُوضع فيه الوجه)
    VIDEO_SWAP_TARGET: int = 21

    # ============================================================
    # حالات لوحة المطور (الإدارة)
    # ============================================================

    # في انتظار كتابة نص الرد لإرساله لمستخدم معين
    ADMIN_REPLY: int = 30

    # في انتظار كتابة نص الرسالة الجماعية
    ADMIN_BROADCAST: int = 31

    # في انتظار إدخال معرف المستخدم لإرسال رسالة مباشرة
    ADMIN_DIRECT_USER_ID: int = 32

    # في انتظار كتابة نص الرسالة المباشرة
    ADMIN_DIRECT_MESSAGE: int = 33

    # في انتظار إدخال معرف المستخدم لحظره
    ADMIN_BAN_USER: int = 34

    # في انتظار إدخال معرف المستخدم لفك الحظر
    ADMIN_UNBAN_USER: int = 35

    # في انتظار إدخال معرف المستخدم لحذفه نهائياً
    ADMIN_DELETE_USER: int = 36

    # في انتظار رفع ملف قاعدة بيانات جديد
    ADMIN_UPLOAD_DB: int = 37

    # في انتظار إدخال اسم نسخة احتياطية للاستعادة
    ADMIN_RESTORE_BACKUP: int = 38
