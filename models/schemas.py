# ================================================================
# مجلد models
# ------------
# هذا المجلد يحتوي على تعريفات البيانات (Data Models / Schemas)
# التي تمثل بنية الجداول والسجلات في قاعدة البيانات.
#
# نستخدم مكتبة Pydantic لأنها:
#   1. تتحقق من صحة البيانات وأنواعها تلقائياً.
#   2. توفر توثيقاً واضحاً لكل حقل.
#   3. تسهل التحويل بين قاموس (dict) وكائن (Model).
#
# ملاحظة للتطوير المستقبلي:
# عند التحويل إلى PostgreSQL لاحقاً، يمكن استخدام هذه النماذج
# نفسها مع SQLAlchemy / SQLModel دون تغيير باقي الكود.
# ================================================================

from typing import Optional

from pydantic import BaseModel


# ----------------------------------------------------------------
# نموذج المستخدم
# ----------------------------------------------------------------
class UserRecord(BaseModel):
    """
    يمثل سجلاً كاملاً لمستخدم في قاعدة البيانات.
    مطابق لأعمدة جدول users.
    """

    # معرف المستخدم الرقمي في تيليجرام (المفتاح الأساسي)
    user_id: int

    # اسم المستخدم (Username) بدون @
    username: Optional[str] = None

    # الاسم الأول (من حساب تيليجرام)
    first_name: Optional[str] = None

    # الاسم الأخير (من حساب تيليجرام) - قد يكون فارغاً
    last_name: Optional[str] = None

    # هل المستخدم محظور؟
    is_banned: bool = False

    # هل المستخدم موافق على المراقبة الشفافة؟
    monitoring_agreed: bool = False

    # تفضيلات المستخدم (JSON نصي) مثل مستوى جودة التحسين
    prefs: str = "{}"

    # عدد الصور التي تم تبديلها
    total_images: int = 0

    # عدد الفيديوهات التي تم تبديلها
    total_videos: int = 0

    # عدد الطلبات الإجمالي
    total_requests: int = 0

    # تاريخ أول تسجيل (ISO نصي)
    created_at: Optional[str] = None

    # تاريخ آخر ظهور (ISO نصي)
    last_seen: Optional[str] = None


# ----------------------------------------------------------------
# نموذج عملية التبديل
# ----------------------------------------------------------------
class SwapRecord(BaseModel):
    """
    يمثل سجلاً لعملية تبديل وجه واحدة (صورة أو فيديو).
    مطابق لأعمدة جدول swaps.
    """

    # معرف المستخدم الذي قام بالعملية
    user_id: int

    # نوع العملية: image أو video
    type: str

    # الحالة: processing / done / failed
    status: str = "processing"

    # مسار الملف المصدر (صورة الوجه)
    source_file: Optional[str] = None

    # مسار الملف الهدف (الصورة أو الفيديو)
    target_file: Optional[str] = None

    # مسار ملف النتيجة
    result_file: Optional[str] = None

    # مدة المعالجة بالثواني
    duration: Optional[float] = None

    # نص الخطأ إن حدث
    error: Optional[str] = None

    # تاريخ العملية (ISO نصي)
    created_at: Optional[str] = None


# ----------------------------------------------------------------
# نموذج رسالة
# ----------------------------------------------------------------
class MessageRecord(BaseModel):
    """
    يمثل رسالة وصلت للبوت من أي مستخدم.
    تُستخدم للمراقبة الشفافة ولعرض الرسائل للمطور.
    """

    # معرف المستخدم المرسل
    user_id: int

    # اسم المستخدم (Username)
    username: Optional[str] = None

    # اسم المرسل الكامل
    name: Optional[str] = None

    # نوع الرسالة: text / photo / video / document ...
    message_type: str

    # نص الرسالة (إن وجد)
    text: Optional[str] = None

    # معرف الملف في تيليجرام (إن كانت رسالة تحتوي ملفاً)
    file_id: Optional[str] = None

    # هل تم الرد على الرسالة من قبل المطور؟
    replied: bool = False

    # نص الرد الذي أرسله المطور
    reply_text: Optional[str] = None

    # وقت وصول الرسالة (ISO نصي)
    created_at: Optional[str] = None


# ----------------------------------------------------------------
# نموذج خطأ
# ----------------------------------------------------------------
class ErrorRecord(BaseModel):
    """
    يمثل خطأ حدث أثناء تشغيل البوت.
    يُسجل في قاعدة البيانات ويُعرض للمطور.
    """

    # معرف المستخدم المرتبط بالخطأ (قد يكون فارغاً)
    user_id: Optional[int] = None

    # المكان الذي حدث فيه الخطأ (اسم المعالج أو الدالة)
    handler: Optional[str] = None

    # نص الخطأ الكامل
    message: str

    # وقت حدوث الخطأ (ISO نصي)
    created_at: Optional[str] = None


# ----------------------------------------------------------------
# نموذج نسخة احتياطية
# ----------------------------------------------------------------
class BackupRecord(BaseModel):
    """
    يمثل نسخة احتياطية لقاعدة البيانات.
    """

    # اسم ملف النسخة الاحتياطية
    filename: str

    # حجم الملف بالبايت
    size: int

    # تاريخ الإنشاء (ISO نصي)
    created_at: Optional[str] = None


# ----------------------------------------------------------------
# نموذج الإحصائيات
# ----------------------------------------------------------------
class StatsSnapshot(BaseModel):
    """
    يمثل لقطة إحصائيات كاملة للوحة المطور.
    يجمع البيانات من عدة جداول وقيم النظام.
    """

    # عدد المستخدمين الإجمالي
    users: int = 0

    # عدد الصور المبدلة
    images: int = 0

    # عدد الفيديوهات المبدلة
    videos: int = 0

    # عدد الطلبات الإجمالي
    requests: int = 0

    # عدد الرسائل المستلمة
    messages: int = 0

    # عدد الأخطاء
    errors: int = 0

    # وقت تشغيل النظام بالثواني
    uptime_seconds: int = 0

    # استهلاك الذاكرة بالميغابايت
    memory_mb: float = 0.0

    # استخدام المعالج بالنسبة المئوية
    cpu_percent: float = 0.0
